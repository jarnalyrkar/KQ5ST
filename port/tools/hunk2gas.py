"""Convert an Amiga hunk executable (split by hunks.py) into a GNU as source file.

Every hunk becomes a labelled block `hunkN` in section .data (TOS does not protect text, and
Prog writes into its own code/data hunks). Relocated longwords are emitted as `.long hunkT+off`,
so the linker produces the relocations. BSS space (allocation larger than stored data) is emitted
as zeros. Byte patches are applied at generation time.

    hunk2gas.py HUNKDIR ORIGINAL_EXE OUT.s [PATCHFILE]

PATCHFILE lines:  <hunk> <hex offset> <expected hex bytes> <replacement hex bytes>   # comment
Replacement "JMP:symbol" emits "jmp symbol" (6 bytes; expected bytes must be at least 6 long, the rest
is kept). Use it to redirect a Prog routine to shim code.
Replacement "RELADD:delta:count" (expected bytes "-") adds delta to `count` consecutive relocated
longwords starting at the offset (e.g. to skip the first instruction of routines in a pointer table).
"""
import json, os, struct, sys

hd, exe, out = sys.argv[1], sys.argv[2], sys.argv[3]
patchfile = sys.argv[4] if len(sys.argv) > 4 else None
hunks = json.load(open(os.path.join(hd, 'hunks.json')))

# allocation sizes from the hunk header (memory size may exceed stored data size)
d = open(exe, 'rb').read(); L = lambda o: struct.unpack('>I', d[o:o+4])[0]
p = 4
while L(p): p += 4
p += 4; first, last = L(p + 4), L(p + 8); p += 12
alloc = [(L(p + 4 * i) & 0x3fffffff) * 4 for i in range(last - first + 1)]

data = {}
for i, h in enumerate(hunks):
    path = os.path.join(hd, f'hunk{i:02d}.bin')
    data[i] = bytearray(open(path, 'rb').read()) if os.path.exists(path) else bytearray()

jumps = {}; reladd = []
if patchfile:
    for line in open(patchfile):
        line = line.split('#')[0].split()
        if not line: continue
        h, off = int(line[0]), int(line[1], 16)
        if line[3].startswith('RELADD:'):
            _, delta, count = line[3].split(':')
            reladd.append((h, off, int(delta), int(count)))
            continue
        exp = bytes.fromhex(line[2])
        got = bytes(data[h][off:off + len(exp)])
        if got != exp: sys.exit(f'patch mismatch hunk {h} +{off:x}: have {got.hex()} expected {exp.hex()}')
        if line[3].startswith('JMP:'):
            assert len(exp) >= 6, line
            jumps[(h, off)] = line[3][4:]
            continue
        rep = bytes.fromhex(line[3]); assert len(exp) == len(rep), line
        data[h][off:off + len(rep)] = rep

o = open(out, 'w')
o.write('| generated by hunk2gas.py - do not edit\n\t.data\n\t.even\n')
for i, h in enumerate(hunks):
    size = alloc[i]; b = data[i]
    rel = {}
    for tgt, offs in h['relocs'].items():
        for off in offs:
            rel[off] = (int(tgt), struct.unpack('>I', bytes(b[off:off + 4]))[0])
    for (rh, roff, delta, count) in reladd:
        if rh != i: continue
        for k in range(count):
            assert roff + 4 * k in rel, f'RELADD: no relocation at hunk {i} +{roff + 4 * k:x}'
            t, v = rel[roff + 4 * k]; rel[roff + 4 * k] = (t, v + delta)
    o.write(f'\n\t.balign 4\n\t.globl hunk{i}\nhunk{i}:\t| {h["type"]} {len(b)} bytes, alloc {size}\n')
    pos = 0; buf = []
    def flush():
        global buf
        for k in range(0, len(buf), 16):
            o.write('\t.byte ' + ','.join(str(x) for x in buf[k:k + 16]) + '\n')
        buf = []
    while pos < len(b):
        if (i, pos) in jumps:
            flush(); o.write(f'\t.short 0x4ef9\n\t.long {jumps[(i, pos)]}\n'); pos += 6
            assert not any(pos - 6 < r < pos for r in rel), f'jump patch overlaps a relocation in hunk {i}'
            continue
        if pos in rel:
            flush(); t, v = rel[pos]; o.write(f'\t.long hunk{t}+0x{v:x}\n'); pos += 4
        else:
            buf.append(b[pos]); pos += 1
    flush()
    if size > len(b): o.write(f'\t.space {size - len(b)}\n')
o.write('\n\t.balign 4\n\t.globl prog_end\nprog_end:\n')
o.close()
print(f'wrote {out}: {len(hunks)} hunks, {sum(alloc)} bytes')
